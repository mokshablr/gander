"""
Writes app/src/main/assets/viewer/xlsx-tables.js: Excel's 60 built-in table styles, which a workbook
names and never holds, as the page draws them. Read from presetTableStyles.xml, ECMA-376's list of
them, as Apache POI keeps a copy:

  curl -sSfLO https://raw.githubusercontent.com/apache/poi/trunk/poi-ooxml/src/main/resources/org/apache/poi/xssf/usermodel/presetTableStyles.xml
  python3 scripts/table-styles/make.py presetTableStyles.xml

Each family of seven styles is one shape in seven colours: the first in the text colour, the rest
in the theme's six accents. So each is written once, with "A" standing for its accent, and the
page puts the colour in. Dark 8 to 11 are each their own.
"""
import json
import sys
from pathlib import Path
from xml.etree import ElementTree as ET

OUT = Path(__file__).resolve().parents[2] / "app/src/main/assets/viewer/xlsx-tables.js"

# The elements the page draws, in the order Excel lays them over each other, the last on top
ELEMENTS = ["wholeTable", "firstColumnStripe", "secondColumnStripe", "firstRowStripe", "secondRowStripe",
            "lastColumn", "firstColumn", "headerRow", "totalRow", "firstHeaderCell", "lastHeaderCell",
            "firstTotalCell", "lastTotalCell"]
SIDES = {"left": "l", "right": "r", "top": "t", "bottom": "b", "horizontal": "h", "vertical": "v"}
FAMILIES = [("Light", 1, 7), ("Light", 8, 14), ("Light", 15, 21), ("Medium", 1, 7), ("Medium", 8, 14),
            ("Medium", 15, 21), ("Medium", 22, 28), ("Dark", 1, 7)]
SINGLES = [("Dark", 8), ("Dark", 9), ("Dark", 10), ("Dark", 11)]


def colour(el, accent):
    """[theme, tint] with the accent as "A", or an RGB value"""
    if el is None:
        return None
    a = el.attrib
    if "theme" in a:
        theme = int(a["theme"])
        tint = round(float(a.get("tint", 0)), 4)
        return ["A" if accent is not None and theme == accent else theme] + ([tint] if tint else [])
    if "rgb" in a:
        return a["rgb"][-6:].upper()
    return None


def dxf(el, accent):
    out = {}
    font = el.find("font")
    if font is not None:
        if font.find("b") is not None:
            out["bold"] = 1
        if font.find("i") is not None:
            out["italic"] = 1
        ink = colour(font.find("color"), accent)
        if ink is not None:
            out["ink"] = ink
    pattern = el.find("fill/patternFill")
    if pattern is not None:
        fill = colour(pattern.find("bgColor"), accent) or colour(pattern.find("fgColor"), accent)
        if fill is not None:
            out["fill"] = fill
    border = el.find("border")
    if border is not None:
        for side, key in SIDES.items():
            line = border.find(side)
            if line is not None and line.get("style"):
                out[key] = [line.get("style"), colour(line.find("color"), accent)]
    return out


def style(root, name, accent):
    el = root.find(name)
    dxfs = [dxf(d, accent) for d in el.find("dxfs")]
    out = {}
    for item in el.find("tableStyles/tableStyle"):
        kind = item.get("type")
        if kind not in ELEMENTS:
            continue
        # POI's copy numbers each style's own formats from one
        look = dict(dxfs[int(item.get("dxfId")) - 1])
        if item.get("size") and item.get("size") != "1":
            look["size"] = int(item.get("size"))
        out[kind] = look
    return out


def main():
    root = ET.parse(sys.argv[1]).getroot()
    shapes = {}
    for family, first, last in FAMILIES:
        for n in range(first, last + 1):
            # The first of a family is drawn in the text colour, theme 1; the rest in accents 1 to 6
            accent = None if n == first else 4 + n - first - 1
            shapes[f"{family}{n}"] = style(root, f"TableStyle{family}{n}", accent)
    for family, n in SINGLES:
        shapes[f"{family}{n}"] = style(root, f"TableStyle{family}{n}", None)
    # Each family's six accented styles are the same once their accent is "A": keep one
    table = {}
    for family, first, last in FAMILIES:
        table[f"{family}{first}"] = shapes[f"{family}{first}"]
        accented = shapes[f"{family}{first + 1}"]
        for n in range(first + 2, last + 1):
            assert shapes[f"{family}{n}"] == accented, f"{family}{n} is not {family}{first + 1} in another colour"
        table[f"{family}{first + 1}-{last}"] = accented
    for family, n in SINGLES:
        table[f"{family}{n}"] = shapes[f"{family}{n}"]
    body = json.dumps(table, separators=(",", ":"), sort_keys=True)
    OUT.write_text(
        "/*\n"
        " * Excel's built-in table styles, which a workbook names and never holds: generated by\n"
        " * scripts/table-styles/make.py from ECMA-376's presetTableStyles.xml. Edit that, not this.\n"
        " *\n"
        " * By name less TableStyle, as Medium2; a family's six accented styles are one entry, \"Medium2-7\",\n"
        " * whose \"A\" is the accent, theme colour 4 for the first. Each element is a look over the part of\n"
        " * the table it names: fill, ink, bold, italic, and border sides l, r, t, b, h and v, each as a line\n"
        " * and a colour, a colour as [theme, tint] or a value. size is how many rows or columns a stripe is.\n"
        " */\n"
        "var VW_TABLE_STYLES = " + body + ";\n"
        "var VW_TABLE_ELEMENTS = " + json.dumps(ELEMENTS) + ";\n"
    )
    print(f"{OUT.relative_to(OUT.parents[5])}: {len(table)} entries, {OUT.stat().st_size:,} bytes")


if __name__ == "__main__":
    main()
